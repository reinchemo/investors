-- Employee payroll configuration foundation
-- Draft only: reviewed in a feature branch; do not apply to production until
-- management/payroll adviser confirms holiday and leave-pay policies.

create table if not exists public.payroll_public_holidays (
  id bigint generated by default as identity primary key,
  holiday_date date not null,
  holiday_name text not null check (length(btrim(holiday_name)) between 2 and 160),
  country_code text not null default 'KE' check (country_code ~ '^[A-Z]{2}$'),
  region text,
  is_active boolean not null default true,
  source_reference text,
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  updated_at timestamptz,
  updated_by uuid references auth.users(id),
  unique (holiday_date, country_code, coalesce(region, ''))
);

create index if not exists payroll_public_holidays_active_date_idx
  on public.payroll_public_holidays (holiday_date)
  where is_active = true;

comment on table public.payroll_public_holidays is
  'Management-maintained public holiday calendar. No holiday dates are preloaded; verify official Kenyan dates before activating.';

create table if not exists public.payroll_leave_pay_policies (
  id bigint generated by default as identity primary key,
  leave_type text not null check (length(btrim(leave_type)) between 2 and 80),
  is_paid boolean not null,
  paid_day_limit integer check (paid_day_limit is null or paid_day_limit >= 0),
  effective_from date not null,
  effective_to date,
  policy_notes text,
  requires_adviser_review boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  updated_at timestamptz,
  updated_by uuid references auth.users(id),
  check (effective_to is null or effective_to >= effective_from)
);

create index if not exists payroll_leave_pay_policy_lookup_idx
  on public.payroll_leave_pay_policies (leave_type, effective_from, effective_to)
  where is_active = true;

comment on table public.payroll_leave_pay_policies is
  'Effective-dated paid/unpaid treatment for leave types. Policies are intentionally not seeded; obtain company and legal/payroll approval first.';

alter table public.payroll_public_holidays enable row level security;
alter table public.payroll_leave_pay_policies enable row level security;

drop policy if exists payroll_public_holidays_select on public.payroll_public_holidays;
create policy payroll_public_holidays_select
  on public.payroll_public_holidays
  for select to authenticated
  using (portal_account_is_active() or portal_management_can_view('Payroll'));

drop policy if exists payroll_public_holidays_insert on public.payroll_public_holidays;
create policy payroll_public_holidays_insert
  on public.payroll_public_holidays
  for insert to authenticated
  with check (portal_management_can_create('Payroll'));

drop policy if exists payroll_public_holidays_update on public.payroll_public_holidays;
create policy payroll_public_holidays_update
  on public.payroll_public_holidays
  for update to authenticated
  using (portal_management_can_edit('Payroll'))
  with check (portal_management_can_edit('Payroll'));

drop policy if exists payroll_public_holidays_delete on public.payroll_public_holidays;
create policy payroll_public_holidays_delete
  on public.payroll_public_holidays
  for delete to authenticated
  using (portal_management_can_delete('Payroll'));

