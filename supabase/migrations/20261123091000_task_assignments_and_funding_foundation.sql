-- STARLINK task assignment and segregated funding foundation.
ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS assignment_mode text NOT NULL DEFAULT 'single'
    CHECK (assignment_mode IN ('single','everyone_must_complete','first_to_claim','open_pool')),
  ADD COLUMN IF NOT EXISTS service_status text NOT NULL DEFAULT 'not_started'
    CHECK (service_status IN ('not_started','on_the_way','arrived','blocked','waiting_for_materials','working','finished')),
  ADD COLUMN IF NOT EXISTS recurrence_rule text,
  ADD COLUMN IF NOT EXISTS recurrence_parent_id text REFERENCES public.tasks(id);

CREATE TABLE IF NOT EXISTS public.task_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id text NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  staff_id bigint NOT NULL REFERENCES public.staff(id),
  assignment_state text NOT NULL DEFAULT 'assigned'
    CHECK (assignment_state IN ('assigned','claimed','accepted','in_progress','awaiting_review','approved','rejected','completed','declined')),
  progress_pct integer NOT NULL DEFAULT 0 CHECK (progress_pct BETWEEN 0 AND 100),
  assigned_at timestamptz NOT NULL DEFAULT now(),
  claimed_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(task_id, staff_id)
);
CREATE INDEX IF NOT EXISTS task_assignments_staff_state_idx ON public.task_assignments(staff_id, assignment_state);
CREATE INDEX IF NOT EXISTS task_assignments_task_idx ON public.task_assignments(task_id);

INSERT INTO public.task_assignments(task_id, staff_id, assignment_state, progress_pct, assigned_at, completed_at)
SELECT t.id, t.assignee_staff_id,
  CASE t.status WHEN 'accepted' THEN 'accepted' WHEN 'in_progress' THEN 'in_progress'
    WHEN 'awaiting_review' THEN 'awaiting_review' WHEN 'approved' THEN 'approved'
    WHEN 'rejected' THEN 'rejected' WHEN 'completed' THEN 'completed' ELSE 'assigned' END,
  COALESCE(t.progress_pct,0), COALESCE(t.created_at,now()), t.completed_at
FROM public.tasks t WHERE t.assignee_staff_id IS NOT NULL
ON CONFLICT (task_id,staff_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.funding_parties (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 legal_name text NOT NULL CHECK(length(btrim(legal_name)) BETWEEN 2 AND 180),
 contact_name text, email text, phone text,
 party_type text NOT NULL DEFAULT 'individual' CHECK(party_type IN ('individual','company')),
 kyc_status text NOT NULL DEFAULT 'not_started' CHECK(kyc_status IN ('not_started','pending','verified','rejected','expired')),
 kyc_reference text, notes text,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','active','suspended','closed')),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.funding_opportunities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reference_code text NOT NULL UNIQUE,
 title text NOT NULL CHECK(length(btrim(title)) BETWEEN 3 AND 180),
 description text, project_id bigint REFERENCES public.projects(id),
 target_amount numeric(14,2) NOT NULL CHECK(target_amount > 0),
 currency_code text NOT NULL DEFAULT 'KES' CHECK(currency_code ~ '^[A-Z]{3}$'),
 proposed_return_rate numeric(8,4) CHECK(proposed_return_rate IS NULL OR proposed_return_rate >= 0),
 term_days integer CHECK(term_days IS NULL OR term_days BETWEEN 1 AND 3650),
 opens_on date, closes_on date,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_approval','approved','open','paused','closed','cancelled')),
 legal_approval_reference text, finance_approval_reference text,
 approved_by uuid REFERENCES auth.users(id), approved_at timestamptz,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(closes_on IS NULL OR opens_on IS NULL OR closes_on >= opens_on),
 CHECK(status NOT IN ('approved','open') OR (legal_approval_reference IS NOT NULL AND finance_approval_reference IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS public.funding_commitments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 opportunity_id bigint NOT NULL REFERENCES public.funding_opportunities(id),
 funder_id bigint NOT NULL REFERENCES public.funding_parties(id),
 principal_amount numeric(14,2) NOT NULL CHECK(principal_amount > 0),
 currency_code text NOT NULL DEFAULT 'KES' CHECK(currency_code ~ '^[A-Z]{3}$'),
 agreed_return_rate numeric(8,4) NOT NULL CHECK(agreed_return_rate >= 0),
 term_days integer NOT NULL CHECK(term_days BETWEEN 1 AND 3650),
 maturity_date date,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_agreement','committed','funds_pending','funded','matured','settled','cancelled')),
 agreement_reference text, signed_at timestamptz, terms_locked_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(opportunity_id,funder_id,id),
 CHECK(status NOT IN ('committed','funds_pending','funded','matured','settled') OR (agreement_reference IS NOT NULL AND signed_at IS NOT NULL AND terms_locked_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS public.funding_receipts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 commitment_id bigint NOT NULL REFERENCES public.funding_commitments(id),
 amount numeric(14,2) NOT NULL CHECK(amount > 0), currency_code text NOT NULL DEFAULT 'KES',
 received_on date NOT NULL DEFAULT current_date, payment_method text, external_reference text,
 verification_status text NOT NULL DEFAULT 'pending' CHECK(verification_status IN ('pending','verified','rejected')),
 verified_by uuid REFERENCES auth.users(id), verified_at timestamptz, notes text, created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(verification_status <> 'verified' OR (verified_by IS NOT NULL AND verified_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS public.funding_settlements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 commitment_id bigint NOT NULL REFERENCES public.funding_commitments(id),
 principal_paid numeric(14,2) NOT NULL DEFAULT 0 CHECK(principal_paid >= 0),
 return_paid numeric(14,2) NOT NULL DEFAULT 0 CHECK(return_paid >= 0),
 paid_on date, payment_reference text,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_approval','approved','paid','cancelled')),
 approved_by uuid REFERENCES auth.users(id), approved_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(status NOT IN ('approved','paid') OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)),
 CHECK(status <> 'paid' OR (paid_on IS NOT NULL AND payment_reference IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS public.funding_project_allocations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 commitment_id bigint NOT NULL REFERENCES public.funding_commitments(id),
 project_id bigint NOT NULL REFERENCES public.projects(id),
 allocated_amount numeric(14,2) NOT NULL CHECK(allocated_amount > 0),
 allocation_date date NOT NULL DEFAULT current_date, notes text,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.funding_liability_ledger (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 commitment_id bigint NOT NULL REFERENCES public.funding_commitments(id),
 receipt_id bigint REFERENCES public.funding_receipts(id),
 settlement_id bigint REFERENCES public.funding_settlements(id),
 entry_type text NOT NULL CHECK(entry_type IN ('principal_received','principal_repaid','return_paid','adjustment')),
 amount numeric(14,2) NOT NULL CHECK(amount > 0), currency_code text NOT NULL DEFAULT 'KES',
 effective_date date NOT NULL DEFAULT current_date, reference text,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.funding_audit_log (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity_type text NOT NULL, entity_id bigint NOT NULL, action text NOT NULL,
 before_data jsonb, after_data jsonb, actor_id uuid REFERENCES auth.users(id),
 created_at timestamptz NOT NULL DEFAULT now()
);
